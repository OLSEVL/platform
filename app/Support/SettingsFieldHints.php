    /** HTML-абзац подсказки (уже экранированный текст). */
    public static function p(string $text): string
    {
        if ($text === '') {
            return '';
        }

        return '<p class="'.self::CSS.'">'.e($text).'</p>';
    }

    /** Blade: безопасный вывод. */
    public static function render(string $text): string
    {
