    /**
     * Подсказка для параметра индикатора (настройки слоя на графике).
     */
    public static function indicator(string $field): string
    {
        return self::INDICATOR[$field]
            ?? self::COMMON[$field]
            ?? self::guess($field);
    }

    /**
     * Подсказка для параметра бота (карточка «Настройки»).
     *
     * @param  string|null  $botType  Тип бота — нужен для min_confidence (формула разная).
     */
    public static function bot(string $field, ?string $botType = null): string
    {
        // У каждого бота confidence считается по-своему — отдаём текст «из чего складывается».
        if ($field === 'min_confidence') {
            return self::minConfidenceHint($botType);
        }

        return self::BOT[$field]
            ?? self::COMMON[$field]
            ?? self::guess($field);
    }

