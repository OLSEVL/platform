    private static function guess(string $field): string
    {
        $f = strtolower($field);
        if (str_contains($f, 'color')) {
            return 'Цвет линии/зоны на графике. Можно писать код (#22c55e) или имя (lime, red). На торговлю не влияет — только как выглядит.';
        }
        if (str_contains($f, 'width')) {
            return 'Толщина линии в пикселях. Больше — линия заметнее. На расчёт индикатора не влияет.';
        }
        if (str_contains($f, 'length') || str_contains($f, 'period') || str_ends_with($f, '_len') || preg_match('/(^|_)sma_len/', $f)) {
            return 'Сколько последних свечей участвует в расчёте. Больше число = линия спокойнее и «медленнее»; меньше = быстрее реагирует, но больше ложных движений.';
        }
        if (str_contains($f, 'show_')) {
            return 'Показать или спрятать этот элемент на графике. Выключение не меняет формулу — только убирает картинку.';
        }
        if (str_contains($f, 'level_') || str_contains($f, 'overbought') || str_contains($f, 'oversold')) {
            return 'Горизонтальный уровень-ориентир на осцилляторе. Выше/ниже него зона считается «дорогой» или «дешёвой». На сами линии индикатора не влияет — это визуальный и/или логический порог.';
        }
        if (str_ends_with($f, '_enabled') || $f === 'enabled') {
            return 'Включить или выключить этот блок индикатора. Выкл — слой не считается/не рисуется (и не мешает другим слоям).';
        }
        if (str_contains($f, 'transparency') || str_contains($f, 'alpha')) {
            return 'Прозрачность заливки (0 = не видно, больше = плотнее цвет). Только внешний вид.';
        }
        if (str_contains($f, 'radius')) {
            return 'Размер точки/маркера на графике в пикселях. Больше — заметнее. На расчёт не влияет.';
        }
        if (str_contains($f, 'deviation') || str_contains($f, 'multiplicat') || str_contains($f, 'multiplier') || str_contains($f, '_coef') || str_contains($f, 'factor')) {
            return 'Множитель/отступ: насколько далеко отодвинуть линию или зону от цены/середины. Больше — шире и спокойнее; меньше — ближе к цене и чувствительнее.';
        }

        return 'Параметр влияет на расчёт или отображение. Если не уверены — оставьте значение по умолчанию и смотрите, как меняется картинка на графике.';
    }

